(function () {
    'use strict';

    function toKey(name) {
        return String(name)
            .replace(/\.html?$/i, '')
            .toLowerCase();
    }

    function applyGameLabels() {
        if (
            !window.gameLabels ||
            typeof window.gameLabels !== 'object'
        ) {
            return false;
        }

        const buttons = document.querySelectorAll(
            '.buttons-container input[type="button"]'
        );

        let changed = 0;

        buttons.forEach((btn) => {
            if (btn.dataset.labeled === '1') return;

            const raw = btn.value;
            btn.dataset.originalValue = raw;

            const key = toKey(raw);
            const label = window.gameLabels[key];

            if (label) {
                btn.value = label;
                btn.dataset.labeled = '1';
                changed++;
            } else {
                console.warn(
                    '[labels] No label for:',
                    raw,
                    '->',
                    key
                );
            }
        });

        if (changed) {
            console.log(`[labels] Applied ${changed} label(s)`);
        }

        return true;
    }

    window.applyGameLabels = applyGameLabels;

    function startObserver() {
        const target = document.getElementById('sections-container');

        if (!target) return;

        const observer = new MutationObserver(() => {
            applyGameLabels();
        });

        observer.observe(target, {
            childList: true,
            subtree: true
        });
    }

    function init() {
        applyGameLabels();
        startObserver();
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }
})();
